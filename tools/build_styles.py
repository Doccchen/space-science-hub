"""Build the three main-page style entries without changing cascade order."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT/'web'
GROUPS = {
    'base.css': ('style.css',),
    'components.css': ('resources.css','glass-theme.css','ai.css','frontend-refinement.css','quiet-ui.css'),
    'pages.css': ('editorial.css','ai-layout.css','site-motion.css','design-system.css','site-welcome.css','article.css'),
}


def content(names):
    sections = ['/* Generated by tools/build_styles.py. Edit the named sources, then rebuild. */\n']
    for name in names:
        css = (WEB/name).read_text(encoding='utf-8')
        # Sources originally resolve URLs under /assets/. Preserve that location.
        def rebase(match):
            value = match.group(1).strip().strip('\"\'')
            if not value or value.startswith(('/', '#', 'data:', 'http:', 'https:', 'var(')):
                return match.group(0)
            return 'url("/assets/'+value+'")'
        css = re.sub(r'url\(([^)]+)\)',rebase,css)
        sections.append(f'\n/* Source: {name} */\n'+css.rstrip()+'\n')
    return ''.join(sections).encode('utf-8')


def build(*, check=False):
    target = WEB/'styles'
    if not check:
        target.mkdir(exist_ok=True)
    for name, sources in GROUPS.items():
        data = content(sources)
        path = target/name
        if check:
            if not path.is_file() or path.read_bytes().replace(b'\r\n',b'\n') != data:
                raise SystemExit(f'Style entry is stale: {path}; run python tools/build_styles.py')
        else:
            path.write_bytes(data)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    build(check=parser.parse_args().check)
    print('Main page style entries are current.')
