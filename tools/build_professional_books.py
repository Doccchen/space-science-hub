"""Build the catalog and faithful cover derivatives from reviewed opening pages."""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'artifacts/home-books-20261017'

def valid_isbn(value):
    if not value:return True
    if len(value)==13 and value.isdigit():return sum(int(x)*(1 if i%2==0 else 3) for i,x in enumerate(value))%10==0
    if len(value)==10:return sum((10-i)*(10 if x=='X' else int(x)) for i,x in enumerate(value))%11==0
    return False

def main():
    books=json.loads((ROOT/'content/professional-books.json').read_text(encoding='utf-8'))
    inventory_path=ART/'inventory.json'
    inventory={x['id']:x for x in json.loads(inventory_path.read_text(encoding='utf-8'))} if inventory_path.exists() else {}
    ART.mkdir(parents=True,exist_ok=True)
    assert len(books)==27 and len({x['name'] for x in books})==27
    assert all(b.get('material_type','图书')=='图书' for b in books)
    destination=ROOT/'web/book-covers';destination.mkdir(exist_ok=True)
    output=[];sources=[]
    for book in books:
        assert valid_isbn(book['isbn']), (book['name'],book['isbn'])
        record=dict(book,category='专业图书',kind='book',access='',provider=book['publisher'])
        record.setdefault('language',['中文']);record.setdefault('material_type','图书');record.setdefault('cover_kind','封面')
        opening=ART/book['id']/'page-1.jpg';path=destination/(book['id']+'.webp')
        if opening.is_file():
            image=Image.open(opening).convert('RGB');image.thumbnail((600,860),Image.Resampling.LANCZOS)
            image.save(path,quality=86,method=6)
        else:
            if not path.is_file():raise FileNotFoundError('Missing reviewed cover: '+str(path))
            image=Image.open(path)
        record['cover']='/assets/book-covers/'+path.name
        record['cover_alt']=book['name']+' · '+record['cover_kind']
        output.append(record)
        sources.append({'id':book['id'],'source_file':inventory.get(book['id'],{}).get('filename'),
                        'metadata_pages':([1,2,3,4,5] if book['id']=='book-03' else [1,2,3,4,5,6] if book['id']=='book-15' else [1,2,3,4]),
                        'cover_page':1,'cover_kind':record['cover_kind'],'cover_width':image.width,'cover_height':image.height,
                        'cover_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                        'missing_fields':[k for k in ['authors','publisher','edition','isbn'] if not book[k] or '未标注' in book[k] or '待核对' in book[k]]})
    (ROOT/'web/professional-books.js').write_bytes(('// Generated by tools/build_professional_books.py from reviewed local catalog.\nwindow.ZhihangBooks='+json.dumps(output,ensure_ascii=False,separators=(',',':'))+';\n').encode('utf-8'))
    (ART/'catalog-sources.json').write_text(json.dumps(sources,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'books':len(output),'cover_bytes':sum((destination/(b['id']+'.webp')).stat().st_size for b in books),'heat_transfer_isbn':next(b['isbn'] for b in books if b['name']=='传热学')}))

if __name__=='__main__':main()
